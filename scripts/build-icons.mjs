// Generates src/icons/generated/icons.ts from the Figma snapshot src/icons/figma/icons.json.
//   npm run icons            (writes src/icons/generated/)
//   node scripts/build-icons.mjs --out <dir>   (used by icons:check to compare)

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const outArg = process.argv.indexOf('--out');
const outDir = outArg > -1 ? process.argv[outArg + 1] : join(root, 'src/icons/generated');
const snapshot = JSON.parse(readFileSync(join(root, 'src/icons/figma/icons.json'), 'utf8'));

const icons = [...snapshot.icons].sort((a, b) => a.name.localeCompare(b.name));
const body = icons
  .map((i) => `  ${JSON.stringify(i.name)}: { viewBox: ${JSON.stringify(i.viewBox)}, paths: ${JSON.stringify(i.paths)} },`)
  .join('\n');

const ts = `// GENERATED by scripts/build-icons.mjs. Do not edit by hand.
// Source: Figma file ${snapshot.source.fileKey}, page "${snapshot.source.page}" (${icons.length} icons).

export interface IconData {
  viewBox: string
  paths: readonly { d: string; fillRule?: string }[]
}

export const icons = {
${body}
} as const satisfies Record<string, IconData>

export type IconName = keyof typeof icons

export const iconNames = Object.keys(icons) as IconName[]
`;
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'icons.ts'), ts);
console.log(`Generated ${icons.length} icons\n  ${join(outDir, 'icons.ts').replace(root + '/', '')}`);
